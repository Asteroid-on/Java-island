    private static void put(String name, double lat, double lon) {
        CITY_COORDS.put(name, new double[]{lat, lon});
    }

    /**
     * 根据城市名称查询坐标。
     *
     * @param cityName 城市名称（可带"市"后缀或不带）
     * @return [纬度, 经度] 数组，找不到返回 null
     */
    public static double[] getCoordinates(String cityName) {
        if (cityName == null || cityName.isEmpty()) return null;
        double[] coords = CITY_COORDS.get(cityName);
        if (coords != null) return coords;
        // 去除"市"后缀后重试
        if (cityName.endsWith("市") && cityName.length() > 1) {
            return CITY_COORDS.get(cityName.substring(0, cityName.length() - 1));
        }
        // 追加"市"后缀后重试
        return CITY_COORDS.get(cityName + "市");
    }

    /**
     * 根据坐标查找内置城市表中最近的城市。
     * 用于将 GPS/WiFi 定位的经纬度映射到最近的城市名。
     *
     * @param lat 纬度
     * @param lon 经度
     * @return 最近的城市名称（不带"市"后缀），超过阈值返回 null
     */
    public static String findNearestCity(double lat, double lon) {
        String nearest = null;
        double minDist = Double.MAX_VALUE;
        for (Map.Entry<String, double[]> entry : CITY_COORDS.entrySet()) {
            // 只取不带"市"后缀的 key，避免重复匹配
            String name = entry.getKey();
            if (name.endsWith("市")) continue;
            double[] coords = entry.getValue();
            double dist = Math.pow(lat - coords[0], 2) + Math.pow(lon - coords[1], 2);
            if (dist < minDist) {
                minDist = dist;
                nearest = name;
            }
        }
        // 放宽至5度(~500km)，内蒙古等地广人稀区域的城市间距较大
        if (nearest != null && Math.sqrt(minDist) > MAX_DISTANCE_DEG) {
            return null;
        }
        return nearest;
    }
